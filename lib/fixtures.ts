import type { MadeThisState, Opportunity, Play, RelationshipPath } from "./types";

function isoFrom(base: Date, minutes: number) {
  return new Date(base.getTime() + minutes * 60_000).toISOString();
}

function path(
  id: string,
  name: string,
  role: string,
  type: RelationshipPath["type"],
  strength: number,
  daysSinceFavor: number,
  favorsIn90Days: number,
): RelationshipPath {
  return {
    id,
    name,
    initials: name
      .split(" ")
      .map((part) => part[0])
      .join(""),
    role,
    type,
    strength,
    daysSinceFavor,
    favorsIn90Days,
    evidence: `Synthetic relationship history · ${strength}/100 strength`,
    eligible: true,
  };
}

